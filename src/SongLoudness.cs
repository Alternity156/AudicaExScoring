        private sealed class MoggSongInfo
        {
            public string MoggPath;
            public List<double> Vols;
            public List<double> Pans;

            private static readonly Regex MoggPathRx = new Regex("\\(\\s*mogg_path\\s+\"?([^\"\\)\\s]+)\"?\\s*\\)", RegexOptions.IgnoreCase);
            private static readonly Regex VolsRx = new Regex("\\(\\s*vols\\s*\\(([^\\)]*)\\)", RegexOptions.IgnoreCase);
            private static readonly Regex PansRx = new Regex("\\(\\s*pans\\s*\\(([^\\)]*)\\)", RegexOptions.IgnoreCase);

            public static MoggSongInfo Parse(string text)
            {
                MoggSongInfo info = new MoggSongInfo();
                Match m = MoggPathRx.Match(text);
                if (m.Success) info.MoggPath = m.Groups[1].Value;
                info.Vols = Numbers(VolsRx.Match(text));
                info.Pans = Numbers(PansRx.Match(text));
                return info;
            }

            private static List<double> Numbers(Match m)
            {
                if (!m.Success) return null;
                List<double> list = new List<double>();
                string[] parts = m.Groups[1].Value.Split(new[] { ' ', '\t', '\r', '\n' }, StringSplitOptions.RemoveEmptyEntries);
                for (int i = 0; i < parts.Length; i++)
                {
                    double v;
                    if (double.TryParse(parts[i], NumberStyles.Float, CultureInfo.InvariantCulture, out v)) list.Add(v);
                }
                return list;
            }
        }

        // ── Minimal zip reader (central directory, stored / deflate, no zip64) ──

        private sealed class ZipReader
        {
            public sealed class Entry
            {
                public string Name;
                public int Method;
                public long CompressedSize;
                public long LocalHeaderOffset;
            }

            private readonly Stream stream;
            private readonly List<Entry> entries = new List<Entry>();

            public ZipReader(Stream s)
            {
                stream = s;
                long length = s.Length;
                int tail = (int)Math.Min(length, 65536 + 22);
                byte[] buf = new byte[tail];
                s.Seek(length - tail, SeekOrigin.Begin);
                ReadFully(s, buf, tail);

                int eocd = -1;
                for (int i = tail - 22; i >= 0; i--)
                {
                    if (buf[i] == 0x50 && buf[i + 1] == 0x4b && buf[i + 2] == 0x05 && buf[i + 3] == 0x06)
                    {
                        eocd = i;
                        break;
                    }
                }
                if (eocd < 0) throw new Exception("not a zip (no end of central directory)");

                int count = BitConverter.ToUInt16(buf, eocd + 10);
                long cdOffset = BitConverter.ToUInt32(buf, eocd + 16);
                long cdSize = BitConverter.ToUInt32(buf, eocd + 12);
                if (cdOffset == 0xFFFFFFFF) throw new Exception("zip64 not supported");

                byte[] cd = new byte[cdSize];
                s.Seek(cdOffset, SeekOrigin.Begin);
                ReadFully(s, cd, (int)cdSize);

                int p = 0;
                for (int i = 0; i < count && p + 46 <= cd.Length; i++)
                {
                    if (BitConverter.ToUInt32(cd, p) != 0x02014b50) throw new Exception("bad central directory");
                    int method = BitConverter.ToUInt16(cd, p + 10);
                    long compSize = BitConverter.ToUInt32(cd, p + 20);
                    int nameLen = BitConverter.ToUInt16(cd, p + 28);
                    int extraLen = BitConverter.ToUInt16(cd, p + 30);
                    int commentLen = BitConverter.ToUInt16(cd, p + 32);
                    long localOffset = BitConverter.ToUInt32(cd, p + 42);
                    string name = Encoding.UTF8.GetString(cd, p + 46, nameLen);
                    entries.Add(new Entry { Name = name, Method = method, CompressedSize = compSize, LocalHeaderOffset = localOffset });
                    p += 46 + nameLen + extraLen + commentLen;
                }
            }

            /// <summary>Exact name first, then a match on the file name alone (any folder).</summary>
            public Entry Find(string name)
            {
                name = name.Replace('\\', '/');
                for (int i = 0; i < entries.Count; i++)
                    if (string.Equals(entries[i].Name, name, StringComparison.OrdinalIgnoreCase)) return entries[i];
                string file = Path.GetFileName(name);
                for (int i = 0; i < entries.Count; i++)
                    if (string.Equals(Path.GetFileName(entries[i].Name), file, StringComparison.OrdinalIgnoreCase)) return entries[i];
                return null;
            }

            public Stream Open(Entry e)
            {
                byte[] local = new byte[30];
                stream.Seek(e.LocalHeaderOffset, SeekOrigin.Begin);
                ReadFully(stream, local, 30);
                if (BitConverter.ToUInt32(local, 0) != 0x04034b50) throw new Exception($"bad local header for '{e.Name}'");
                int nameLen = BitConverter.ToUInt16(local, 26);
                int extraLen = BitConverter.ToUInt16(local, 28);
                long dataStart = e.LocalHeaderOffset + 30 + nameLen + extraLen;

                Stream raw = new SubStream(stream, dataStart, e.CompressedSize);
                if (e.Method == 0) return raw;
                if (e.Method == 8) return new DeflateStream(raw, CompressionMode.Decompress);
                throw new Exception($"zip method {e.Method} not supported for '{e.Name}'");
            }
        }

        /// <summary>Read-only window over part of another stream.</summary>
        private sealed class SubStream : Stream
        {
            private readonly Stream inner;
            private readonly long start;
            private readonly long length;
            private long position;

            public SubStream(Stream inner, long start, long length)
            {
                this.inner = inner;
                this.start = start;
                this.length = length;
            }

            public override bool CanRead => true;
            public override bool CanSeek => false;
            public override bool CanWrite => false;
            public override long Length => length;
            public override long Position { get => position; set => throw new NotSupportedException(); }

            public override int Read(byte[] buffer, int offset, int count)
            {
                long left = length - position;
                if (left <= 0) return 0;
                if (count > left) count = (int)left;
                inner.Seek(start + position, SeekOrigin.Begin);
                int n = inner.Read(buffer, offset, count);
                if (n > 0) position += n;
                return n;
            }

            public override void Flush() { }
            public override long Seek(long offset, SeekOrigin origin) => throw new NotSupportedException();
            public override void SetLength(long value) => throw new NotSupportedException();
            public override void Write(byte[] buffer, int offset, int count) => throw new NotSupportedException();
        }


