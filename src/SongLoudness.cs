    /// <summary>
    /// Song loudness for volume normalization (Config.NormalizeSongVolume).
    ///
    /// Where a song's loudness comes from, in order:
    ///  1. OfficialLoudness.Table (generated by measure_official_loudness.py): the official / DLC
    ///     songs, whose moggs are encrypted and can't be measured in game. Only numbers ship.
    ///  2. The on-disk cache (ExScoringSongCache/loudness_cache.json), keyed by the .audica's full
    ///     path, checked against its size and last write time and the algorithm version.
    ///  3. A measurement on the background thread. Songs asked for by the preview / gameplay
    ///     (TryGetGainDb) go first; while in the menus a slow background pass measures the rest of
    ///     the library (paused while a song is being played). Failures (e.g. an encrypted mogg that
    ///     isn't in the table) are cached too, so they aren't retried every boot; they play at 0 dB.
    ///
    /// Measurement (unchanged from the measurement build, matches the Python script):
    ///  - Opens the .audica (a zip) with a small built-in zip reader (stored / deflate).
    ///  - Reads the .moggsong named after the '%' in SongData.moggSong: mogg_path, vols (dB per
    ///    channel) and pans (-1..1 per channel).
    ///  - Reads the .mogg: version 10 = unencrypted (anything else fails as encrypted), the Ogg
    ///    data offset, then decodes the Ogg Vorbis audio packet by packet with csvorbis.
    ///  - Mixes the channels to stereo with the vols and pans (balance pan law), K-weights it and
    ///    gates 400 ms blocks (EBU R128 integrated loudness, LUFS) and tracks the sample peak.
    ///
    /// Gain for a song = target - loudness. Cuts are limited to MaxCutDb; boosts to MaxBoostDb and
    /// to what keeps the song's peak at or below CeilingDb.
    ///
    /// Threading: the worker only touches files and csvorbis. Song paths are resolved on the main
    /// thread, results are applied, cached and logged from the main thread (SongPreview.Update /
    /// AudioDriver.Update postfixes).
    /// </summary>
    internal static class SongLoudness
    {
        private const string Tag = "[Loudness]";

        public const float MaxBoostDb = 6f;
        public const float MaxCutDb = -20f;
        public const float CeilingDb = 0f;

        /// <summary>Bump when the measurement changes, so cached results get measured again.</summary>
        private const int AlgorithmVersion = 1;

        private const float BackgroundStartDelaySeconds = 20f;
        private const int BackgroundSongsPerFrame = 25;
        private const float CacheSaveIntervalSeconds = 15f;

        // ── Known loudness ──

        private sealed class Known
        {
            public bool Ok;
            public float Lufs;
            public float PeakDb;
        }

        [Serializable]
        private sealed class CacheEntry
        {
            public long Size;
            public long Ticks;
            public int Algorithm;
            public bool Ok;
            public float Lufs;
            public float PeakDb;
            public string Error;
        }

        // Main thread only.
        private static readonly Dictionary<string, Known> bySongId = new Dictionary<string, Known>(StringComparer.OrdinalIgnoreCase);
        private static readonly HashSet<string> pending = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        private static Dictionary<string, CacheEntry> cache;
        private static bool cacheDirty;
        private static float lastCacheSave;

        private static readonly string cacheDirectory = Application.dataPath.Replace("Audica_Data", "ExScoringSongCache");
        private static readonly string cacheFilePath = Path.Combine(cacheDirectory, "loudness_cache.json");

        /// <summary>
        /// Gain in dB to apply to a song's audio. True when the answer is final (normalization off,
        /// no song, or the song's loudness is known; failed measurements give 0 dB). False while the
        /// song is still being measured (gainDb = 0); its measurement is moved to the front.
        /// </summary>
        public static bool TryGetGainDb(SongList.SongData song, out float gainDb)
        {
            gainDb = 0f;
            if (!Config.NormalizeSongVolume || song == null) return true;
            string id = song.songID;
            if (string.IsNullOrEmpty(id)) return true;

            Known k;
            if (!bySongId.TryGetValue(id, out k))
            {
                if (pending.Contains(id))
                {
                    PromotePending(song);
                    return false;
                }
                k = Lookup(song);
                if (k == null)
                {
                    Request(song, true);
                    return false;
                }
                bySongId[id] = k;
            }

            if (k.Ok) gainDb = GainFor(k.Lufs, k.PeakDb);
            return true;
        }

        public static float GainFor(float lufs, float peakDb)
        {
            float gain = Config.NormalizeTargetLufs - lufs;
            if (gain > 0f) gain = Mathf.Max(0f, Mathf.Min(gain, Mathf.Min(MaxBoostDb, CeilingDb - peakDb)));
            else gain = Mathf.Max(gain, MaxCutDb);
            return gain;
        }

        /// <summary>Official table, then the disk cache. Null when the song needs measuring.</summary>
        private static Known Lookup(SongList.SongData song)
        {
            OfficialLoudness.Entry official;
            if (OfficialLoudness.TryGet(song.songID, out official))
                return new Known { Ok = true, Lufs = official.Lufs, PeakDb = official.PeakDb };

            string zip = ResolveZip(song);
            if (zip == null) return new Known { Ok = false }; // nothing to measure, plays at 0 dB

            EnsureCacheLoaded();
            CacheEntry e;
            if (cache.TryGetValue(CacheKey(zip), out e) && e.Algorithm == AlgorithmVersion)
            {
                try
                {
                    FileInfo fi = new FileInfo(zip);
                    if (fi.Length == e.Size && fi.LastWriteTimeUtc.Ticks == e.Ticks)
                        return new Known { Ok = e.Ok, Lufs = e.Lufs, PeakDb = e.PeakDb };
                }
                catch { }
            }
            return null;
        }

        private static string CacheKey(string path)
        {
            try { path = Path.GetFullPath(path); } catch { }
            return path.Replace('\\', '/').ToLowerInvariant();
        }

        // ── Cache file ──

        private static void EnsureCacheLoaded()
        {
            if (cache != null) return;
            cache = new Dictionary<string, CacheEntry>();
            try
            {
                if (File.Exists(cacheFilePath))
                {
                    Dictionary<string, CacheEntry> loaded =
                        JsonConvert.DeserializeObject<Dictionary<string, CacheEntry>>(File.ReadAllText(cacheFilePath));
                    if (loaded != null) cache = loaded;
                    DebugLog.Log($"{Tag} loaded {cache.Count} cached results");
                }
            }
            catch (Exception ex)
            {
                MelonLogger.Log($"{Tag} failed to load the loudness cache, starting empty: {ex.Message}");
                cache = new Dictionary<string, CacheEntry>();
            }
        }

        private static void SaveCacheIfDirty(bool force)
        {
            if (!cacheDirty || cache == null) return;
            if (!force && Time.unscaledTime - lastCacheSave < CacheSaveIntervalSeconds) return;
            lastCacheSave = Time.unscaledTime;
            try
            {
                Directory.CreateDirectory(cacheDirectory);
                string tmp = cacheFilePath + ".tmp";
                File.WriteAllText(tmp, JsonConvert.SerializeObject(cache, Formatting.Indented));
                if (File.Exists(cacheFilePath)) File.Delete(cacheFilePath);
                File.Move(tmp, cacheFilePath);
                cacheDirty = false;
                DebugLog.Log($"{Tag} saved {cache.Count} cached results");
            }
            catch (Exception ex)
            {
                MelonLogger.Log($"{Tag} failed to save the loudness cache: {ex.Message}");
            }
        }

        // ── Jobs and results ──

        private sealed class Job
        {
            public string SongId;
            public string ZipPath;
            public string MoggSongEntry;
            public bool Background;
        }

        private sealed class Result
        {
            public Job Job;
            public bool Ok;
            public bool Skipped;
            public string Error;
            public double Lufs;
            public double PeakDb;
            public long Size;
            public long Ticks;
            public int Channels;
            public int Rate;
            public double AudioSeconds;
            public double DecodeSeconds;
            public string MixInfo;
        }

        private static readonly ConcurrentQueue<Job> priorityJobs = new ConcurrentQueue<Job>();
        private static readonly ConcurrentQueue<Job> backgroundJobs = new ConcurrentQueue<Job>();
        private static readonly ConcurrentQueue<Result> results = new ConcurrentQueue<Result>();
        // Worker only: file stamp (size ^ last write) each path was last measured at, so a song
        // queued twice (background, then asked for) is only measured once.
        private static readonly ConcurrentDictionary<string, long> measured = new ConcurrentDictionary<string, long>(StringComparer.OrdinalIgnoreCase);
        private static readonly AutoResetEvent wake = new AutoResetEvent(false);
        private static readonly object workerLock = new object();
        private static Thread worker;
        private static volatile bool backgroundPaused;

        // Main thread: songs queued in the background, to move them up when they're asked for.
        private static readonly Dictionary<string, Job> queuedInBackground = new Dictionary<string, Job>(StringComparer.OrdinalIgnoreCase);

        private static void Request(SongList.SongData song, bool priority)
        {
            Job job = MakeJob(song, !priority);
            if (job == null)
            {
                bySongId[song.songID] = new Known { Ok = false };
                return;
            }
            pending.Add(job.SongId);
            if (priority)
            {
                DebugLog.Log($"{Tag} measuring {job.SongId}");
                Enqueue(priorityJobs, job);
            }
            else
            {
                queuedInBackground[job.SongId] = job;
                Enqueue(backgroundJobs, job);
            }
        }

        /// <summary>A song waiting in the background queue was asked for: measure it next.</summary>
        private static void PromotePending(SongList.SongData song)
        {
            Job queued;
            if (!queuedInBackground.TryGetValue(song.songID, out queued)) return;
            queuedInBackground.Remove(song.songID);
            Job job = new Job { SongId = queued.SongId, ZipPath = queued.ZipPath, MoggSongEntry = queued.MoggSongEntry, Background = false };
            DebugLog.Log($"{Tag} measuring {job.SongId} (moved up from the background pass)");
            Enqueue(priorityJobs, job); // the worker skips the background copy
        }

        private static string ResolveZip(SongList.SongData s)
        {
            string mogg = s.moggSong;
            if (string.IsNullOrEmpty(mogg)) return null;
            int pct = mogg.IndexOf('%');
            if (pct < 0) return null;
            string relZip = mogg.Substring(0, pct);

            string[] candidates = { s.foundPath, relZip, Path.Combine(Application.dataPath, relZip) };
            for (int i = 0; i < candidates.Length; i++)
            {
                string c = candidates[i];
                if (!string.IsNullOrEmpty(c) && c.EndsWith(".audica", StringComparison.OrdinalIgnoreCase) && File.Exists(c))
                    return c;
            }
            return null;
        }

        private static Job MakeJob(SongList.SongData s, bool background)
        {
            string id = s.songID ?? "?";
            string mogg = s.moggSong;
            int pct = string.IsNullOrEmpty(mogg) ? -1 : mogg.IndexOf('%');
            string zip = ResolveZip(s);
            if (pct < 0 || zip == null)
            {
                DebugLog.Log($"{Tag} {id}: no .audica to measure (foundPath '{s.foundPath}', moggSong '{mogg}'), playing at 0 dB");
                return null;
            }
            return new Job { SongId = id, ZipPath = zip, MoggSongEntry = mogg.Substring(pct + 1), Background = background };
        }

        private static void Enqueue(ConcurrentQueue<Job> queue, Job job)
        {
            queue.Enqueue(job);
            EnsureWorker();
            wake.Set();
        }

        // ── Main thread tick ──

        private static int lastFrame = -1;
        private static float firstMenuTime = -1f;
        private static int scanIndex;
        private static int scanListCount = -1;
        private static bool scanAnnounced;
        private static int backgroundQueued;
        private static int backgroundDone;

        private static bool InSong()
        {
            MenuState.State state = MenuState.GetState();
            return state == MenuState.State.Launching || state == MenuState.State.Launched;
        }

        private static void MainThreadTick()
        {
            int frame = Time.frameCount;
            if (frame == lastFrame) return;
            lastFrame = frame;

            bool inSong = InSong();
            backgroundPaused = inSong;

            Result r;
            while (results.TryDequeue(out r)) Apply(r);

            if (!inSong) BackgroundScanStep();
            SaveCacheIfDirty(false);
        }

        /// <summary>
        /// Walks the song list a few songs per frame (after a delay in the menus) and queues every
        /// song whose loudness isn't known yet. Starts over when the song list changes size.
        /// </summary>
        private static void BackgroundScanStep()
        {
            if (!Config.NormalizeSongVolume) return;
            if (firstMenuTime < 0f) firstMenuTime = Time.unscaledTime;
            if (Time.unscaledTime - firstMenuTime < BackgroundStartDelaySeconds) return;

            SongList list = SongList.I;
            if (list == null || list.songs == null) return;
            int count = list.songs.Count;
            if (count != scanListCount)
            {
                scanListCount = count;
                scanIndex = 0;
                scanAnnounced = false;
            }
            if (scanIndex >= count) return;

            int end = Math.Min(count, scanIndex + BackgroundSongsPerFrame);
            for (; scanIndex < end; scanIndex++)
            {
                SongList.SongData s = list.songs[scanIndex];
                if (s == null || string.IsNullOrEmpty(s.songID)) continue;
                if (bySongId.ContainsKey(s.songID) || pending.Contains(s.songID)) continue;
                Known k = Lookup(s);
                if (k != null)
                {
                    bySongId[s.songID] = k;
                    continue;
                }
                Request(s, false);
                if (pending.Contains(s.songID)) backgroundQueued++;
            }

            if (scanIndex >= count && !scanAnnounced)
            {
                scanAnnounced = true;
                DebugLog.Log($"{Tag} background pass: {backgroundQueued - backgroundDone} songs to measure, {bySongId.Count} already known");
            }
        }

        private static void Apply(Result r)
        {
            string id = r.Job.SongId;
            pending.Remove(id);
            queuedInBackground.Remove(id);
            if (r.Skipped) return; // the same file's result was applied just before
            bySongId[id] = new Known { Ok = r.Ok, Lufs = (float)r.Lufs, PeakDb = (float)r.PeakDb };

            EnsureCacheLoaded();
            cache[CacheKey(r.Job.ZipPath)] = new CacheEntry
            {
                Size = r.Size,
                Ticks = r.Ticks,
                Algorithm = AlgorithmVersion,
                Ok = r.Ok,
                Lufs = (float)Math.Round(r.Lufs, 2),
                PeakDb = (float)Math.Round(r.PeakDb, 2),
                Error = r.Ok ? null : r.Error
            };
            cacheDirty = true;

            if (r.Ok)
            {
                double speed = r.DecodeSeconds > 0 ? r.AudioSeconds / r.DecodeSeconds : 0;
                DebugLog.Log($"{Tag} {id}: {r.Lufs:0.0} LUFS, peak {r.PeakDb:0.0} dBFS -> gain {GainFor((float)r.Lufs, (float)r.PeakDb):+0.0;-0.0;0.0} dB " +
                             $"({r.Channels} ch @ {r.Rate} Hz, {r.AudioSeconds:0}s in {r.DecodeSeconds:0.0}s, {speed:0}x, {r.MixInfo}){(r.Job.Background ? " [background]" : "")}");
            }
            else
            {
                DebugLog.Log($"{Tag} {id}: not measured ({r.Error}), playing at 0 dB");
            }

            if (r.Job.Background)
            {
                backgroundDone++;
                if (scanAnnounced && priorityJobs.IsEmpty && backgroundJobs.IsEmpty && pending.Count == 0)
                {
                    DebugLog.Log($"{Tag} background pass finished ({backgroundDone} songs measured)");
                    SaveCacheIfDirty(true);
                }
            }
        }

        // ── Worker thread ──

        private static void EnsureWorker()
        {
            lock (workerLock)
            {
                if (worker != null && worker.IsAlive) return;
                worker = new Thread(WorkerLoop)
                {
                    IsBackground = true,
                    Priority = System.Threading.ThreadPriority.BelowNormal,
                    Name = "ExScoring loudness"
                };
                worker.Start();
            }
        }

        private static void WorkerLoop()
        {
            while (true)
            {
                Job job;
                bool got = priorityJobs.TryDequeue(out job);
                if (!got && !backgroundPaused) got = backgroundJobs.TryDequeue(out job);
                if (!got)
                {
                    wake.WaitOne(500);
                    continue;
                }

                long stamp = 0;
                try
                {
                    FileInfo fi = new FileInfo(job.ZipPath);
                    stamp = fi.Length ^ fi.LastWriteTimeUtc.Ticks;
                }
                catch { }
                long previous;
                if (measured.TryGetValue(job.ZipPath, out previous) && previous == stamp)
                {
                    // Its result is already queued ahead of this one.
                    results.Enqueue(new Result { Job = job, Skipped = true });
                    continue;
                }
                measured[job.ZipPath] = stamp;
                results.Enqueue(Measure(job));
            }
        }

        private static Result Measure(Job job)
        {
            Result r = new Result { Job = job };
            Stopwatch clock = Stopwatch.StartNew();
            try
            {
                FileInfo fi = new FileInfo(job.ZipPath);
                r.Size = fi.Length;
                r.Ticks = fi.LastWriteTimeUtc.Ticks;

                using (FileStream fs = new FileStream(job.ZipPath, FileMode.Open, FileAccess.Read, FileShare.Read, 65536))
                {
                    ZipReader zip = new ZipReader(fs);

                    ZipReader.Entry songEntry = zip.Find(job.MoggSongEntry);
                    if (songEntry == null) throw new Exception($"'{job.MoggSongEntry}' not in the .audica");
                    string moggsong;
                    using (Stream s = zip.Open(songEntry))
                    using (StreamReader sr = new StreamReader(s, Encoding.UTF8))
                        moggsong = sr.ReadToEnd();

                    MoggSongInfo info = MoggSongInfo.Parse(moggsong);
                    if (string.IsNullOrEmpty(info.MoggPath)) throw new Exception("moggsong has no mogg_path");
                    ZipReader.Entry moggEntry = zip.Find(info.MoggPath);
                    if (moggEntry == null) throw new Exception($"mogg '{info.MoggPath}' not in the .audica");

                    using (Stream s = zip.Open(moggEntry))
                    {
                        byte[] header = new byte[8];
                        ReadFully(s, header, 8);
                        int version = BitConverter.ToInt32(header, 0);
                        int oggOffset = BitConverter.ToInt32(header, 4);
                        if (version != 10) throw new Exception($"mogg version {version} (encrypted)");
                        if (oggOffset < 8) throw new Exception($"bad mogg header (ogg offset {oggOffset})");
                        Skip(s, oggOffset - 8);

                        DecodeAndMeasure(s, info, r);
                    }
                }
                r.Ok = true;
            }
            catch (Exception ex)
            {
                r.Ok = false;
                r.Error = ex.Message;
            }
            r.DecodeSeconds = clock.Elapsed.TotalSeconds;
            return r;
        }

        private static void ReadFully(Stream s, byte[] buffer, int count)
        {
            int read = 0;
            while (read < count)
            {
                int n = s.Read(buffer, read, count - read);
                if (n <= 0) throw new EndOfStreamException();
                read += n;
            }
        }

        private static void Skip(Stream s, int count)
        {
            byte[] tmp = new byte[4096];
            while (count > 0)
            {
                int n = s.Read(tmp, 0, Math.Min(tmp.Length, count));
                if (n <= 0) throw new EndOfStreamException();
                count -= n;
            }
        }

        // ── Vorbis decode + mix + loudness ──

        private static void DecodeAndMeasure(Stream input, MoggSongInfo info, Result r)
        {
            SyncState oy = new SyncState();
            StreamState os = new StreamState();
            Page og = new Page();
            Packet op = new Packet();
            Info vi = new Info();
            Comment vc = new Comment();
            DspState vd = new DspState();
            Block vb = new Block(vd);

            oy.init();

            // First page: stream serial and the identification header.
            int index = oy.buffer(4096);
            int bytes = input.Read(oy.data, index, 4096);
            oy.wrote(bytes);
            if (oy.pageout(og) != 1) throw new Exception("not an Ogg stream");
            os.init(og.serialno());
            vi.init();
            vc.init();
            if (os.pagein(og) < 0) throw new Exception("bad first Ogg page");
            if (os.packetout(op) != 1) throw new Exception("no Vorbis header packet");
            if (vi.synthesis_headerin(vc, op) < 0) throw new Exception("not Vorbis audio");

            // Comment and codebook headers.
            int headers = 0;
            while (headers < 2)
            {
                while (headers < 2)
                {
                    int res = oy.pageout(og);
                    if (res == 0) break;
                    if (res == 1)
                    {
                        os.pagein(og);
                        while (headers < 2)
                        {
                            res = os.packetout(op);
                            if (res == 0) break;
                            if (res == -1) throw new Exception("corrupt Vorbis header");
                            vi.synthesis_headerin(vc, op);
                            headers++;
                        }
                    }
                }
                if (headers < 2)
                {
                    index = oy.buffer(4096);
                    bytes = input.Read(oy.data, index, 4096);
                    if (bytes <= 0) throw new Exception("end of file before the Vorbis headers");
                    oy.wrote(bytes);
                }
            }

            int channels = vi.channels;
            r.Channels = channels;
            r.Rate = vi.rate;

            // Per-channel mix gains from the moggsong.
            double[] gl = new double[channels];
            double[] gr = new double[channels];
            bool usedVols = info.Vols != null && info.Vols.Count == channels;
            bool usedPans = info.Pans != null && info.Pans.Count == channels;
            for (int c = 0; c < channels; c++)
            {
                double vol = usedVols ? info.Vols[c] : 0.0;
                double pan = usedPans ? info.Pans[c] : (channels == 1 ? 0.0 : (c % 2 == 0 ? -1.0 : 1.0));
                if (pan < -1) pan = -1; else if (pan > 1) pan = 1;
                double g = Math.Pow(10.0, vol / 20.0);
                gl[c] = g * (pan <= 0 ? 1.0 : 1.0 - pan);
                gr[c] = g * (pan >= 0 ? 1.0 : 1.0 + pan);
            }
            r.MixInfo = $"vols {(usedVols ? "used" : (info.Vols == null ? "missing" : $"ignored ({info.Vols.Count} values)"))}, " +
                        $"pans {(usedPans ? "used" : (info.Pans == null ? "missing" : $"ignored ({info.Pans.Count} values)"))}";

            R128 meter = new R128(vi.rate);

            vd.synthesis_init(vi);
            vb.init(vd);
            float[][][] pcmHolder = new float[1][][];
            int[] pcmIndex = new int[channels];

            bool eos = false;
            while (!eos)
            {
                while (!eos)
                {
                    int res = oy.pageout(og);
                    if (res == 0) break;
                    if (res == -1) continue; // corrupt / missing page, keep going
                    os.pagein(og);
                    while (true)
                    {
                        res = os.packetout(op);
                        if (res == 0) break;
                        if (res == -1) continue;
                        if (vb.synthesis(op) == 0) vd.synthesis_blockin(vb);

                        int samples;
                        while ((samples = vd.synthesis_pcmout(pcmHolder, pcmIndex)) > 0)
                        {
                            float[][] pcm = pcmHolder[0];
                            for (int j = 0; j < samples; j++)
                            {
                                double l = 0, rr = 0;
                                for (int c = 0; c < channels; c++)
                                {
                                    double x = pcm[c][pcmIndex[c] + j];
                                    l += x * gl[c];
                                    rr += x * gr[c];
                                }
                                meter.Add(l, rr);
                            }
                            vd.synthesis_read(samples);
                        }
                    }
                    if (og.eos() != 0) eos = true;
                }
                if (!eos)
                {
                    index = oy.buffer(4096);
                    bytes = input.Read(oy.data, index, 4096);
                    oy.wrote(bytes);
                    if (bytes <= 0) eos = true;
                }
            }

            os.clear();
            vb.clear();
            vd.clear();
            vi.clear();
            oy.clear();

            r.AudioSeconds = meter.Samples / (double)vi.rate;
            r.Lufs = meter.Integrated();
            r.PeakDb = meter.Peak > 0 ? 20.0 * Math.Log10(meter.Peak) : -999.0;
            if (double.IsNegativeInfinity(r.Lufs)) throw new Exception("silent (no block above -70 LUFS)");
        }

        /// <summary>
        /// ITU-R BS.1770-4 integrated loudness for a stereo signal: K-weighting (high shelf + high
        /// pass, coefficients for any sample rate as in libebur128), 400 ms blocks every 100 ms,
        /// absolute gate -70 LUFS, relative gate -10 LU.
        /// </summary>
        private sealed class R128
        {
            private readonly double sb0, sb1, sb2, sa1, sa2; // high shelf
            private readonly double ha1, ha2;               // high pass (b = 1, -2, 1)
            private double lx1, lx2, ly1, ly2, lz1, lz2;     // left: shelf in/out, high pass out
            private double rx1, rx2, ry1, ry2, rz1, rz2;     // right
            private readonly int subLength;
            private int subCount;
            private double subSum;
            private readonly List<double> subBlocks = new List<double>();

            public long Samples;
            public double Peak;

            public R128(int rate)
            {
                double fs = rate;

                double f0 = 1681.974450955533, g = 3.999843853973347, q = 0.7071752369554196;
                double k = Math.Tan(Math.PI * f0 / fs);
                double vh = Math.Pow(10.0, g / 20.0);
                double vb = Math.Pow(vh, 0.4996667741545416);
                double a0 = 1.0 + k / q + k * k;
                sb0 = (vh + vb * k / q + k * k) / a0;
                sb1 = 2.0 * (k * k - vh) / a0;
                sb2 = (vh - vb * k / q + k * k) / a0;
                sa1 = 2.0 * (k * k - 1.0) / a0;
                sa2 = (1.0 - k / q + k * k) / a0;

                f0 = 38.13547087602444;
                q = 0.5003270373238773;
                k = Math.Tan(Math.PI * f0 / fs);
                a0 = 1.0 + k / q + k * k;
                ha1 = 2.0 * (k * k - 1.0) / a0;
                ha2 = (1.0 - k / q + k * k) / a0;

                subLength = Math.Max(1, rate / 10);
            }

            public void Add(double l, double r)
            {
                double al = l < 0 ? -l : l, ar = r < 0 ? -r : r;
                if (al > Peak) Peak = al;
                if (ar > Peak) Peak = ar;

                double ly = sb0 * l + sb1 * lx1 + sb2 * lx2 - sa1 * ly1 - sa2 * ly2;
                lx2 = lx1; lx1 = l;
                double lz = ly - 2.0 * ly1 + ly2 - ha1 * lz1 - ha2 * lz2;
                ly2 = ly1; ly1 = ly;
                lz2 = lz1; lz1 = lz;

                double ry = sb0 * r + sb1 * rx1 + sb2 * rx2 - sa1 * ry1 - sa2 * ry2;
                rx2 = rx1; rx1 = r;
                double rz = ry - 2.0 * ry1 + ry2 - ha1 * rz1 - ha2 * rz2;
                ry2 = ry1; ry1 = ry;
                rz2 = rz1; rz1 = rz;

                subSum += lz * lz + rz * rz;
                Samples++;
                if (++subCount >= subLength)
                {
                    subBlocks.Add(subSum);
                    subSum = 0;
                    subCount = 0;
                }
            }

            public double Integrated()
            {
                int n = subBlocks.Count - 3;
                if (n <= 0) return double.NegativeInfinity;

                double[] z = new double[n];
                double norm = 1.0 / (4.0 * subLength);
                for (int i = 0; i < n; i++)
                    z[i] = (subBlocks[i] + subBlocks[i + 1] + subBlocks[i + 2] + subBlocks[i + 3]) * norm;

                double absGate = Math.Pow(10.0, (-70.0 + 0.691) / 10.0);
                double sum = 0;
                int count = 0;
                for (int i = 0; i < n; i++)
                    if (z[i] > absGate) { sum += z[i]; count++; }
                if (count == 0) return double.NegativeInfinity;

                double relGate = (sum / count) * Math.Pow(10.0, -10.0 / 10.0);
                sum = 0;
                count = 0;
                for (int i = 0; i < n; i++)
                    if (z[i] > absGate && z[i] > relGate) { sum += z[i]; count++; }
                if (count == 0) return double.NegativeInfinity;

                return -0.691 + 10.0 * Math.Log10(sum / count);
            }
        }

